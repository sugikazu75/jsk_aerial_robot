#!/usr/bin/env python3
"""Write the MuJoCo world of the hanging-perching demo of quad_with_dual_arm from the configuration of
the planner (config/quad_with_dual_arm/perching_motion.yaml), so that the simulation has the scene
and the start the plan has:

  worlds/<name>.xml   the robot model generated by catkin build (mujoco/<airframe>/robot.xml) and
                      the bar, its posts and the wall of urdf/environment/perching_environment.urdf.xacro,
                      in a body placed at task_frame [x, y, yaw]
  worlds/<name>.yaml  the initial state: the robot on the floor right below --start (task frame),
                      heading along the task frame, both arms at folded_joints

  rosrun gimbalrotor make_perching_world.py [--config perching_motion.yaml] [--name quad_with_dual_arm_perching]

The root height on the floor is that of the lowest point of the collision meshes of the URDF with the
arms folded (plus --clearance). Run it again whenever the scene, the start or the folded arms change.
"""

import argparse
import os
import struct
import subprocess

import numpy as np
import pinocchio as pin
import rospkg
import yaml

ARMS = ("front_arm", "back_arm")


def resolve(path):
    if path.startswith("package://"):
        package, _, rest = path[len("package://") :].partition("/")
        return os.path.join(rospkg.RosPack().get_path(package), rest)
    return path


def stl_vertices(path):
    with open(path, "rb") as f:
        data = f.read()
    if data[:5] == b"solid" and b"facet" in data[:512]:  # ascii
        return np.array(
            [
                [float(v) for v in line.split()[1:4]]
                for line in data.decode().splitlines()
                if line.strip().startswith("vertex")
            ]
        )
    n = struct.unpack("<I", data[80:84])[0]
    facets = np.frombuffer(data[84 : 84 + 50 * n], dtype=np.dtype([("n", "<3f4"), ("v", "<9f4"), ("a", "<u2")]))
    return facets["v"].reshape(-1, 3).astype(float)


def lowest_point(urdf, folded):
    """The lowest z of the collision meshes with the root at the origin, level, and the arms folded."""
    model = pin.buildModelFromXML(urdf, pin.JointModelFreeFlyer())
    package_dir = os.path.dirname(rospkg.RosPack().get_path("gimbalrotor"))
    geom = pin.buildGeomFromUrdfString(model, urdf, pin.GeometryType.COLLISION, package_dirs=[package_dir])
    data, gdata = model.createData(), geom.createData()
    q = pin.neutral(model)
    for arm in ARMS:
        for k, angle in enumerate(folded):
            q[model.joints[model.getJointId("%s_joint%d" % (arm, k + 1))].idx_q] = angle
    pin.forwardKinematics(model, data, q)
    pin.updateGeometryPlacements(model, data, geom, gdata)
    low = np.inf
    for i, obj in enumerate(geom.geometryObjects):
        if obj.meshPath and os.path.exists(obj.meshPath):
            v = stl_vertices(obj.meshPath) * obj.meshScale
            low = min(low, float((gdata.oMg[i].rotation @ v.T)[2].min() + gdata.oMg[i].translation[2]))
    return low


def main():
    package = rospkg.RosPack().get_path("gimbalrotor")
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument(
        "--config", default=os.path.join(package, "config", "quad_with_dual_arm", "perching_motion.yaml")
    )
    parser.add_argument("--name", default="quad_with_dual_arm_perching", help="worlds/<name>.xml and .yaml")
    parser.add_argument("--airframe", default="quad_with_dual_arm")
    parser.add_argument("--bar-length", type=float, default=1.2, help="[m] (that of the xacro)")
    parser.add_argument("--clearance", type=float, default=0.002, help="[m] of the lowest point above the floor")
    args = parser.parse_args()
    with open(args.config) as f:
        c = yaml.safe_load(f)
    tx, ty, yaw = (float(v) for v in c.get("task_frame", [0.0, 0.0, 0.0]))
    bar_x, bar_z, radius, wall_x = (float(c[k]) for k in ("bar_x", "bar_z", "bar_radius", "wall_x"))
    folded = [float(v) for v in c["folded_joints"]]
    half = args.bar_length / 2

    urdf = subprocess.run(["xacro", resolve(c["robot"])], check=True, capture_output=True, text=True).stdout
    root_z = -lowest_point(urdf, folded) + args.clearance
    start = np.array([float(v) for v in c["start"]])
    rotation = pin.rpy.rpyToMatrix(0.0, 0.0, yaw)
    root = rotation @ np.array([start[0], start[1], 0.0]) + np.array([tx, ty, 0.0])
    quat = pin.Quaternion(rotation)

    xml = """<!-- Generated by scripts/simulation/make_perching_world.py from {config}: do not edit, run it again.
     MuJoCo world of the hanging-perching demo of quad_with_dual_arm: the robot model generated by
     catkin build (config/mujoco_model.yaml) and the scene of urdf/environment/perching_environment.urdf.xacro
     (bar_x {bar_x}, bar_z {bar_z}, bar_radius {radius}, bar_length {length}, wall_x {wall_x}) in the task
     frame, placed at task_frame [{tx}, {ty}, {yaw}].

     Load it by an absolute path (roslaunch $(find ...)): MuJoCo resolves the relative include inside
     robot.xml from the path given.

       roslaunch gimbalrotor bringup.launch real_machine:=false simulation:=true airframe:={airframe} \\
         mujoco:=true mujoco_world:={name} -->
<mujoco model="{name}">
  <include file="../mujoco/{airframe}/robot.xml"/>

  <worldbody>
    <body name="env_task" pos="{tx} {ty} 0" euler="0 0 {yaw}">
      <!-- the bar along y; priority so that its friction (that of the plan) is the one used against
           the robot, whose geoms have the default friction 1 -->
      <geom name="env_bar" type="cylinder" size="{radius} {half}" pos="{bar_x} 0 {bar_z}" euler="1.5708 0 0"
            rgba="0.80 0.13 0.12 1" friction="{friction} 0.005 0.0001" priority="1"/>
      <!-- the posts holding the bar, just outside its ends -->
      <geom name="env_post_left" type="box" size="0.02 0.02 {post_half}" pos="{bar_x} {post_y} {post_z}" rgba="0.70 0.72 0.75 1"/>
      <geom name="env_post_right" type="box" size="0.02 0.02 {post_half}" pos="{bar_x} {post_y_neg} {post_z}" rgba="0.70 0.72 0.75 1"/>
      <!-- the wall, its face at x = wall_x facing +x (task frame) -->
      <geom name="env_wall" type="box" size="0.025 0.8 1.2" pos="{wall_c} 0 1.2" rgba="0.90 0.90 0.87 0.6"
            friction="{friction} 0.005 0.0001" priority="1"/>
    </body>
  </worldbody>
</mujoco>
""".format(
        config=os.path.relpath(args.config, package),
        name=args.name,
        airframe=args.airframe,
        bar_x=bar_x,
        bar_z=bar_z,
        radius=radius,
        length=args.bar_length,
        half=half,
        wall_x=wall_x,
        tx=tx,
        ty=ty,
        yaw=yaw,
        friction=float(c.get("friction", 0.5)),
        post_half=(bar_z + 2 * radius) / 2,
        post_y=half + 0.02,
        post_y_neg=-(half + 0.02),
        post_z=(bar_z + 2 * radius) / 2,
        wall_c=wall_x - 0.025,
    )
    joints = {
        "root_joint": "%.4f %.4f %.4f %.6f %.6f %.6f %.6f" % (root[0], root[1], root_z, quat.w, quat.x, quat.y, quat.z)
    }
    for arm in ARMS:
        for k, angle in enumerate(folded):
            joints["%s_joint%d" % (arm, k + 1)] = "%.4f" % angle
    state = (
        "# Generated by scripts/simulation/make_perching_world.py from %s: do not edit, run it again.\n"
        "# Initial state of the MuJoCo world %s.xml: on the floor below the hover position (start),\n"
        "# heading along the task frame, the arms folded (folded_joints).\n"
        "# root_joint (free joint): x y z qw qx qy qz\n" % (os.path.relpath(args.config, package), args.name)
        + yaml.safe_dump({"initial_joint_positions": {"joint_map": joints}}, default_flow_style=False)
    )
    worlds = os.path.join(package, "worlds")
    for ext, text in (("xml", xml), ("yaml", state)):
        path = os.path.join(worlds, "%s.%s" % (args.name, ext))
        with open(path, "w") as f:
            f.write(text)
        print("wrote", path)
    print("root on the floor at (%.3f, %.3f, %.3f), yaw %.3f; arms %s" % (root[0], root[1], root_z, yaw, folded))


if __name__ == "__main__":
    main()
